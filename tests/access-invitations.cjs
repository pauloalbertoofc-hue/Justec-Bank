"use strict";
const assert = require("node:assert/strict");
const { once } = require("node:events");
const { chromium } = require("playwright");
const { fixture, PASSWORD } = require("./lab-fixture.cjs");
const { createServer } = require("../server/http.cjs");
(async () => {
  const cleanups = [];
  const f = await fixture({ after: fn => cleanups.push(fn) });
  const server = createServer(f.db, { rateLimit: false, now: () => f.lab.now() });
  server.listen(0, "127.0.0.1");
  await once(server, "listening");
  const origin = `http://127.0.0.1:${server.address().port}`;
  const browser = await chromium.launch({ executablePath: process.env.CHROMIUM_PATH || "/usr/bin/chromium", args: ["--no-sandbox"] });
  try {
    const page = await browser.newPage({ viewport: { width: 375, height: 850 } });
    const errors = [];
    page.on("pageerror", e => errors.push(e.message));
    const requests = [];
    page.on("request", r => requests.push(r.url()));
    const invitation = f.lab.invite(f.admin, f.sessionId, { role: "researcher" });
    await page.goto(origin + "/laboratorio/#convite=" + invitation.code);
    await page.locator("#login-form").waitFor();
    assert.equal(new URL(page.url()).hash, "");
    assert(await page.locator("#invitation-notice").isVisible());
    assert.equal(requests.some(url => url.includes(invitation.code)), false);
    await page.locator("#access-help summary").click();
    assert.match(await page.locator("#access-help").innerText(), /atendimento verificado/);
    await page.locator("#register-access summary").click();
    await page.locator("#register-form [name=alias]").fill("new-researcher");
    await page.locator("#register-form [name=password]").fill(PASSWORD);
    await page.locator("#register-form [name=consent]").check();
    await page.locator("#register-form button").click();
    await page.waitForFunction(() => document.querySelector("#login-form [name=alias]").value === "new-researcher");
    await page.locator("#login-form [name=password]").fill(PASSWORD);
    await page.locator("#login-form button").click();
    await page.locator("#join-form").waitFor();
    assert.equal(await page.locator("#join-form [name=code]").inputValue(), invitation.code);
    assert.equal(f.db.prepare("SELECT consumed_by FROM invitations WHERE token_hash=?").get(require("../server/security.cjs").hash(invitation.code)).consumed_by, null);
    await page.locator("#join-form button[type=submit]").click();
    await page.locator("#home-security").waitFor();
    const user = f.db.prepare("SELECT id,global_role FROM users WHERE alias=?").get("new-researcher");
    assert.equal(user.global_role, "participant");
    assert.equal(f.db.prepare("SELECT role FROM memberships WHERE user_id=? AND session_id=?").get(user.id, f.sessionId).role, "researcher");
    assert(await page.locator("#admin-switch").isVisible());
    assert.equal(f.db.prepare("SELECT COUNT(*) AS n FROM accounts WHERE owner_id=?").get(user.id).n, 0);
    await page.locator("#logout").click();
    await page.locator("#login-form").waitFor();
    assert.equal(await page.locator("#invitation-notice").isVisible(), false);
    await page.locator("#login-form [name=alias]").fill(f.admin.alias);
    await page.locator("#login-form [name=password]").fill(PASSWORD);
    await page.locator("#login-form button").click();
    await page.locator("#admin-switch").waitFor();
    await page.locator("#admin-switch").click();
    await page.locator('[data-view="research"]').click();
    await page.locator('#invite-form [name=role]').selectOption("participant");
    await page.locator('#invite-form button[type=submit]').click();
    const generated = page.locator('#invite-form [name=invitationLink]');
    await generated.waitFor();
    const link = new URL(await generated.inputValue());
    assert.equal(link.origin, origin);
    assert.equal(link.pathname, "/laboratorio/");
    assert.equal(link.search, "");
    assert.equal(new URLSearchParams(link.hash.slice(1)).get("convite"), await page.locator('#invite-form [name=invitation]').inputValue());
    assert.equal(await generated.getAttribute("readonly"), "");
    await page.locator('#invite-form [name=role]').selectOption("researcher");
    await page.locator('#invite-form button[type=submit]').click();
    await page.waitForFunction(() => document.querySelectorAll('#invite-form [name=invitationLink]').length === 2, null, { timeout: 5000 });
    const secondCode = await page.locator('#invite-form [name=invitation]').nth(1).inputValue();
    assert.notEqual(secondCode, new URLSearchParams(link.hash.slice(1)).get("convite"));
    assert.equal(f.db.prepare("SELECT role FROM invitations WHERE token_hash=?").get(require("../server/security.cjs").hash(secondCode)).role, "researcher");
    await page.locator("#security-shortcut").click();
    await page.locator("#issue-recovery-form [name=password]").fill(PASSWORD);
    await page.locator("#issue-recovery-form button[type=submit]").click();
    const codeField = page.getByLabel("Código de recuperação", { exact: true });
    await codeField.waitFor();
    const recoveryCode = await codeField.inputValue();
    assert.match(recoveryCode, /^[A-Za-z0-9_-]{43}$/);
    await page.locator("#logout").click();
    await page.locator("#login-form").waitFor();
    assert.equal(await page.locator(".recovery-result").count(), 0);
    if (!await page.locator("#recovery-form").isVisible())
      await page.locator("#access-help summary").click();
    await page.locator("#recovery-form [name=alias]").fill(f.admin.alias);
    await page.locator("#recovery-form [name=code]").fill(recoveryCode);
    await page.locator("#recovery-form [name=password]").fill("new-browser-exclusive-password");
    await page.locator("#recovery-form button[type=submit]").click();
    await page.waitForFunction(() => document.querySelector("#lab-feedback").textContent.includes("Senha redefinida"));
    await page.locator("#login-form [name=password]").fill("new-browser-exclusive-password");
    await page.locator("#login-form button").click();
    await page.locator("#admin-switch").waitFor();
    assert.deepEqual(errors, []);
    console.log("PASS: convite no fragmento sem envio em URL, cadastro sem privilégios globais, confirmação explícita, papel pesquisador e logout; recuperação administrativa completa com nova senha.");
  } finally {
    await browser.close();
    await new Promise(resolve => server.close(resolve));
    for (const cleanup of cleanups.reverse()) await cleanup();
  }
})().catch(e => { console.error(e); process.exitCode = 1; });
